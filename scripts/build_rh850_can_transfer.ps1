param(
    [Parameter(Mandatory=$true)][string]$DeviceProject,
    [switch]$Prepare
)
$ErrorActionPreference='Stop'
$root=(Resolve-Path -LiteralPath $DeviceProject).Path
$project=Join-Path $root 'Sample_Project_RH850_S1_CAN_Transfer.mtpj'
if(!(Test-Path -LiteralPath $project -PathType Leaf)){throw 'Expected the RH850 Classical Transfer project.'}
. (Join-Path $root 'tools\evm_prepare.ps1')
. (Join-Path $root 'tools\can_v4_project.ps1')
Update-EvmClock $root
$logRoot=Join-Path (Split-Path -Parent $PSScriptRoot) 'tmp\internal\rh850'
New-Item -ItemType Directory -Path $logRoot -Force | Out-Null
if($Prepare){
    [xml]$xml=Get-Content -LiteralPath $project -Raw
    Set-EvmProject $root $xml
    $files=$xml.CubeSuiteProject.Class | Where-Object {$_.Guid -eq '68f4a651-b9cd-473b-a595-b00447132ffa'}
    if(!$files){throw 'Unknown CS+ project structure.'}
    $backup=Join-Path $logRoot ('transfer_mtpj_'+(Get-Date -Format 'yyyyMMdd_HHmmss_fff')+'.bak')
    Copy-Item -LiteralPath $project -Destination $backup
    # Exclude the copied UART-command/demo runtime, not the actual CAN driver.
    foreach($node in @($files.Instance | Where-Object {$_.Type -eq 'File'})){
        if([string]$node.RelativePath -in @('custom_func.c','misc_config.c','retarget.c','hal\can\rs_canfd_sample_app.c','src\smc_gen\general\r_cg_cgc.c','src\smc_gen\general\r_cg_intvector.c','src\smc_gen\general\r_smc_intprg.c')){
            [void]$files.RemoveChild($node)
        }
    }
    $parent=[string]$xml.SelectSingleNode('//FileCategoryGuid').InnerText
    # One complete table, one default handler; no per-slot duplicate ISR bodies.
    # Channel numbers come from the R7F701684 SC interrupt vector projection.
    $mapping=@{23='rs_canfd_rx_fifo_interrupt';34='r_Config_UART0_interrupt_send';35='r_Config_UART0_interrupt_receive';36='r_Config_UART0_interrupt_error';80='r_Config_TAUJ0_0_interrupt';84='r_Config_OSTM0_interrupt'}
    $generated=New-Object Text.StringBuilder
    [void]$generated.AppendLine('/* Generated by build_rh850_can_transfer.ps1; R7F701684 EIINT channel indexes. */')
    [void]$generated.AppendLine('#include "r_cg_macrodriver.h"')
    foreach($name in @($mapping.Values | Sort-Object)){[void]$generated.AppendLine(('extern void '+$name+'(void);'))}
    [void]$generated.AppendLine('#pragma interrupt Device_UnhandledIsr(enable=false, fpu=true, callt=false)')
    [void]$generated.AppendLine('void Device_UnhandledIsr(void) { DI(); for (;;) { NOP(); } }')
    [void]$generated.AppendLine('#pragma section const "EIINTTBL"')
    [void]$generated.AppendLine('void (* const INT_Vectors[512])(void) = {')
    for($i=0;$i -lt 512;$i++){
        $name=if($mapping.ContainsKey($i)){$mapping[$i]}else{'Device_UnhandledIsr'}
        [void]$generated.AppendLine(('    '+$name+', /* EIINT '+$i+' */'))
    }
    [void]$generated.AppendLine('};')
    $projection=Join-Path $root 'generated_projection'
    New-Item -ItemType Directory -Path $projection -Force | Out-Null
    [IO.File]::WriteAllText((Join-Path $projection 'device_vectors.c'),$generated.ToString(),(New-Object Text.UTF8Encoding($false)))
    foreach($path in @('transfer_main.c','rh850_can.c','rh850_can.h','rh850_can_ports.c','rh850_can_ports.h','can_port_config.h','device_types.h','can_transfer_protocol.c','can_transfer_protocol.h','can_transfer_config.h','generated_projection\device_vectors.c','generated_projection\evm_clock.c')){
        if(!(Test-Path -LiteralPath (Join-Path $root $path))){throw "Missing source: $path"}
        if(@($files.Instance | Where-Object {$_.RelativePath -eq $path}).Count){continue}
        $item=$xml.CreateElement('Instance');$item.SetAttribute('Guid',[guid]::NewGuid().ToString())
        $image=if([IO.Path]::GetExtension($path) -eq '.c'){'941832c1-fc3b-4e1b-94e8-01ea17128b42'}else{'03cad1e8-2eb3-4cde-a8a3-982423631122'}
        foreach($pair in @{Name=$path;Type='File';RelativePath=$path;TreeImageGuid=$image;ParentItem=$parent}.GetEnumerator()){
            $child=$xml.CreateElement($pair.Key);$child.InnerText=$pair.Value;[void]$item.AppendChild($child)
        }
        [void]$files.AppendChild($item)
    }
    $xml.SelectSingleNode('//COptionLangC-0').InnerText='None'
    $xml.SelectSingleNode('//PreBuildCommands-0').InnerText='powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%ProjectDir%\tools\evm_prepare.ps1" -ClockProject "%ProjectDir%\."'
    if(!(Test-Path -LiteralPath (Join-Path $root 'tools\verify_transfer.ps1'))){throw 'Missing local Transfer linked-image verifier.'}
    $xml.SelectSingleNode('//PostBuildCommands-0').InnerText='powershell.exe -NoProfile -ExecutionPolicy Bypass -File "%ProjectDir%\tools\verify_transfer.ps1" -DeviceProject "%ProjectDir%\."'
    # Code starts at1000h; the vector table still starts at200h.
    $xml.SelectSingleNode('//LinkOptionStart-0').InnerText='RESET/00000000,EIINTTBL.const/00000200,.const,.INIT_DSEC.const,.INIT_BSEC.const,.text,.data/00001000,.data.R,.bss,.stack.bss/FEDF0000'
    foreach($node in @($xml.SelectNodes('//*[not(*)]') | Where-Object {$_.LocalName -like 'ProjectGeneratr-GeneratedFile*'})){
        if($node.InnerText -match '^[A-Za-z]:[\\/]'){$node.InnerText=[IO.Path]::GetFileName($node.InnerText)}
    }
    Set-CanV4Project -Xml $xml -Project $root -SourceRoot ''
    $writer=New-Object Xml.XmlWriterSettings
    $writer.Indent=$true;$writer.OmitXmlDeclaration=$true;$writer.NewLineChars="`r`n"
    $writer.Encoding=New-Object Text.UTF8Encoding($false)
    $stream=[Xml.XmlWriter]::Create($project,$writer)
    try{$xml.Save($stream)}finally{$stream.Dispose()}
}
$compiler=Join-Path ${env:ProgramFiles(x86)} 'Renesas Electronics\CS+\CC\CubeSuite+.exe'
if(!(Test-Path -LiteralPath $compiler)){throw 'CS+ CC is required; no additional firmware build runtime is used.'}
$log=Join-Path $logRoot 'can_transfer_rebuild.log'
$proc=Start-Process -FilePath $compiler -ArgumentList ('/br "'+$project+'"') -RedirectStandardOutput $log -RedirectStandardError ($log+'.stderr') -WindowStyle Hidden -PassThru -Wait
$result=Get-Content -LiteralPath $log -Raw
$result -split '\r?\n' | Select-Object -Last 14 | Write-Host
if($result -notmatch 'Build ended\(Error:0, Warning:\d+\)' -or $result -match 'Failed:[1-9]'){
    throw "RH850 clean rebuild failed: $log"
}
$hex=Join-Path $root 'DefaultBuild\Sample_Project_RH850_S1_CAN_Transfer.mot'
if(!(Test-Path -LiteralPath $hex)){throw 'No current programmer image.'}
& (Join-Path $PSScriptRoot 'verify_rh850_transfer.ps1') -DeviceProject $root
Write-Host ('PASS: CC-RH rebuild; programmer MOT SHA256 '+(Get-FileHash -LiteralPath $hex).Hash)
Write-Host 'Hardware/COM/Flash tests NOT RUN.'
